using System.Text;

namespace Ascube.Mwm.Core.PatientName;

/// <summary>
/// 半角カナ → 全角カナの自前変換表（実装指示書 v2 T7）。
/// ⚠ ﾀﾞ は「ﾀ」+「ﾞ」の2文字で来る。全角化では「ダ」の1文字に結合する（半濁点も同様）。
/// 変換表に無い文字（漢字・ASCII・既に全角の文字等）はそのまま通す。
/// </summary>
public static class HalfToFullWidthKana
{
    // 濁点・半濁点の結合（2文字 → 1文字）。基底カナ＋ﾞ/ﾟ の並びだけを対象にする。
    private static readonly Dictionary<string, char> Combining = new()
    {
        ["ｶﾞ"] = 'ガ', ["ｷﾞ"] = 'ギ', ["ｸﾞ"] = 'グ', ["ｹﾞ"] = 'ゲ', ["ｺﾞ"] = 'ゴ',
        ["ｻﾞ"] = 'ザ', ["ｼﾞ"] = 'ジ', ["ｽﾞ"] = 'ズ', ["ｾﾞ"] = 'ゼ', ["ｿﾞ"] = 'ゾ',
        ["ﾀﾞ"] = 'ダ', ["ﾁﾞ"] = 'ヂ', ["ﾂﾞ"] = 'ヅ', ["ﾃﾞ"] = 'デ', ["ﾄﾞ"] = 'ド',
        ["ﾊﾞ"] = 'バ', ["ﾋﾞ"] = 'ビ', ["ﾌﾞ"] = 'ブ', ["ﾍﾞ"] = 'ベ', ["ﾎﾞ"] = 'ボ',
        ["ｳﾞ"] = 'ヴ',
        ["ﾊﾟ"] = 'パ', ["ﾋﾟ"] = 'ピ', ["ﾌﾟ"] = 'プ', ["ﾍﾟ"] = 'ペ', ["ﾎﾟ"] = 'ポ',
    };

    // 単独文字の変換表（濁点・半濁点がもう付かない場合に使う）。
    private static readonly Dictionary<char, char> Single = new()
    {
        ['ｦ'] = 'ヲ', ['ｧ'] = 'ァ', ['ｨ'] = 'ィ', ['ｩ'] = 'ゥ', ['ｪ'] = 'ェ', ['ｫ'] = 'ォ',
        ['ｬ'] = 'ャ', ['ｭ'] = 'ュ', ['ｮ'] = 'ョ', ['ｯ'] = 'ッ', ['ｰ'] = 'ー',
        ['ｱ'] = 'ア', ['ｲ'] = 'イ', ['ｳ'] = 'ウ', ['ｴ'] = 'エ', ['ｵ'] = 'オ',
        ['ｶ'] = 'カ', ['ｷ'] = 'キ', ['ｸ'] = 'ク', ['ｹ'] = 'ケ', ['ｺ'] = 'コ',
        ['ｻ'] = 'サ', ['ｼ'] = 'シ', ['ｽ'] = 'ス', ['ｾ'] = 'セ', ['ｿ'] = 'ソ',
        ['ﾀ'] = 'タ', ['ﾁ'] = 'チ', ['ﾂ'] = 'ツ', ['ﾃ'] = 'テ', ['ﾄ'] = 'ト',
        ['ﾅ'] = 'ナ', ['ﾆ'] = 'ニ', ['ﾇ'] = 'ヌ', ['ﾈ'] = 'ネ', ['ﾉ'] = 'ノ',
        ['ﾊ'] = 'ハ', ['ﾋ'] = 'ヒ', ['ﾌ'] = 'フ', ['ﾍ'] = 'ヘ', ['ﾎ'] = 'ホ',
        ['ﾏ'] = 'マ', ['ﾐ'] = 'ミ', ['ﾑ'] = 'ム', ['ﾒ'] = 'メ', ['ﾓ'] = 'モ',
        ['ﾔ'] = 'ヤ', ['ﾕ'] = 'ユ', ['ﾖ'] = 'ヨ',
        ['ﾗ'] = 'ラ', ['ﾘ'] = 'リ', ['ﾙ'] = 'ル', ['ﾚ'] = 'レ', ['ﾛ'] = 'ロ',
        ['ﾜ'] = 'ワ', ['ﾝ'] = 'ン',
        ['ﾞ'] = '゛', ['ﾟ'] = '゜',
        ['｡'] = '。', ['｢'] = '「', ['｣'] = '」', ['､'] = '、', ['･'] = '・',
    };

    public static string Convert(string input)
    {
        var sb = new StringBuilder(input.Length);
        var i = 0;
        while (i < input.Length)
        {
            if (i + 1 < input.Length)
            {
                var pair = input.Substring(i, 2);
                if (Combining.TryGetValue(pair, out var combined))
                {
                    sb.Append(combined);
                    i += 2;
                    continue;
                }
            }

            sb.Append(Single.TryGetValue(input[i], out var single) ? single : input[i]);
            i++;
        }

        return sb.ToString();
    }
}
